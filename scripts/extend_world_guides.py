def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="给海上/极地环线新增城市补完整攻略")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    cities = data.get("cities") or []
    by_name = {c.get("name"): c for c in cities}

    missing = [n for n in GUIDES if n not in by_name]
    if missing:
        print(f"⚠ 目录里没有这些城市，先跑 extend_world_loops.py：{'、'.join(missing)}", file=sys.stderr)
        return 2

    filled, skipped = [], []
    for name, patch in GUIDES.items():
        card = by_name[name]
        days = patch["guide"]["days"]
        if len(patch["guide"]["itinerary"]) != days:
            print(f"⚠ {name} 的天数 {days} 与逐日条目 {len(patch['guide']['itinerary'])} 不一致", file=sys.stderr)
            return 3
        if card.get("guide"):
            skipped.append(name)
            continue
        card.update(patch)
        card["days"] = days
        filled.append(name)

    print(f"补攻略：{len(filled)} 座 → {'、'.join(filled) or '（无）'}")
    if skipped:
        print(f"已有攻略、跳过：{'、'.join(skipped)}")
    for name in filled:
        card = by_name[name]
        print(f"  {name}：{card['guide']['days']} 天 / {len(card['guide']['itinerary'])} 条逐日 / "
              f"{len(card['highlights'])} 个看点")

    if args.dry_run:
        print("（dry-run：没写文件）")
        return 0

    CATALOG.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"✓ 已写入 {CATALOG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
